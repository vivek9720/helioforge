size_t marker_score(const uint8_t* data, size_t size, const std::string& marker) {
  if (marker.empty()) return 0;
  return find_marker(data, size, marker).size() * 8;
}

size_t size_score(size_t size, size_t min_size, size_t max_size) {
  if (min_size != 0 && size < min_size) return 0;
  if (max_size != 0 && size > max_size) return 0;
  size_t score = 2;
  if (min_size != 0 && size >= min_size) score += 2;
  if (max_size != 0 && size <= max_size) score += 1;
  return score;
}

