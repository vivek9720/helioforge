RuleEngine::RuleEngine(std::vector<RuleSpec> rules) : rules_(std::move(rules)) {}

std::vector<RuleHit> RuleEngine::evaluate(const uint8_t* data, size_t size) const {
  ByteProfile profile = profile_bytes(data, size, 48);
  std::vector<RuleHit> hits;
  for (const auto& rule : rules_) {
    size_t confidence = size_score(size, rule.min_size, rule.max_size);
    confidence += marker_score(data, size, rule.marker);
    if (rule.requires_text) {
      if (!looks_like_text(data, size)) continue;
      confidence += 4;
    }
    if (rule.field == "entropy" && !profile.windows.empty()) {
      for (const auto& window : profile.windows) {
        if (window.entropy > 3.5) ++confidence;
      }
    }
    if (rule.field == "varint") {
      for (size_t off = 0; off < std::min<size_t>(size, 32); ++off) {
        if (read_varint(data, size, off).ok) ++confidence;
      }
    }
    if (confidence >= 6) {
      RuleHit hit;
      hit.family = rule.family;
      hit.name = rule.name;
      hit.severity = rule.severity;
      hit.confidence = confidence;
      hit.detail = rule.description;
      hits.push_back(std::move(hit));
    }
  }
  std::sort(hits.begin(), hits.end(), [](const RuleHit& a, const RuleHit& b) {
    if (a.confidence != b.confidence) return a.confidence > b.confidence;
    if (a.family != b.family) return a.family < b.family;
    return a.name < b.name;
  });
  if (hits.size() > 256) hits.resize(256);
  return hits;
}

const std::vector<RuleSpec>& default_rule_catalog() {
  static const std::vector<RuleSpec> rules = build_catalog();
  return rules;
}

std::vector<RuleHit> evaluate_default_rules(const uint8_t* data, size_t size) {
  RuleEngine engine(default_rule_catalog());
  return engine.evaluate(data, size);
}

std::string severity_name(RuleSeverity severity) {
  switch (severity) {
    case RuleSeverity::kInfo: return "info";
    case RuleSeverity::kWarning: return "warning";
    case RuleSeverity::kError: return "error";
  }
  return "info";
}

std::string render_rule_hits(const std::vector<RuleHit>& hits, size_t limit) {
  std::ostringstream out;
  size_t shown = 0;
  for (const auto& hit : hits) {
    if (shown++ >= limit) break;
    out << hit.family << ":" << hit.name << " " << severity_name(hit.severity)
        << " confidence=" << hit.confidence << " " << hit.detail << "\n";
  }
  return out.str();
}

